"""The land under the Links box's line map (the owner's design note of 2026-10-19): Natural Earth's
1:50m countries (public domain), clipped to the Baltic region and drawn in the map's own projection —
longitude scaled by the cosine of the middle latitude — as SVG paths in app/src/ui/basemap.ts.
1:50m since D-206: the 1:110m file had none of Estonia's islands, Saaremaa, Hiiumaa and Muhu.
The file is Natural Earth 5.1.1's ne_50m_admin_0_countries.zip (799 734 bytes, sha256 5fed4333…b853139),
https://naciscdn.org/naturalearth/50m/cultural/ne_50m_admin_0_countries.zip, unzipped outside the
repository; v4's environment has geopandas:
  ../energiamudel-v4.nosync/.venv/bin/python -I spikes/basemap/basemap.py <dir>/ne_50m_admin_0_countries.shp
(from the repository's root)"""
import math
import sys
from pathlib import Path

import geopandas as gpd
from shapely.geometry import box

SHP = Path(sys.argv[1])
LON0, LON1, LAT0, LAT1 = 14.0, 29.0, 53.6, 60.5
COS = math.cos(math.radians((LAT0 + LAT1) / 2))
W = 340
K = W / ((LON1 - LON0) * COS)
H = round((LAT1 - LAT0) * K)
HOME = {"Estonia": "EE", "Latvia": "LV", "Lithuania": "LT"}
# 0.02° is under a pixel at the map's scale (1° of latitude is K ≈ 42 px): the coast loses nothing the eye sees
SIMPLIFY = 0.02

g = gpd.read_file(SHP)
# a degree of land around the box, a degree and a half east: the deck's map moves east to give Estonia's price room
# right of its node (D-252)
clip = box(LON0 - 1, LAT0 - 1, LON1 + 1.5, LAT1 + 1)
out = []
for _, r in g.iterrows():
    geom = r.geometry.intersection(clip)
    if geom.is_empty:
        continue
    polys = geom.geoms if geom.geom_type == "MultiPolygon" else [geom]
    d = ""
    for p in polys:
        if p.geom_type != "Polygon" or p.area < 0.01:
            continue
        p = p.simplify(SIMPLIFY, preserve_topology=True)
        pts = [((lon - LON0) * COS * K, (LAT1 - lat) * K) for lon, lat in p.exterior.coords]
        d += "M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + "Z"
    if d:
        out.append((HOME.get(r["NAME"], ""), r["NAME"], d))

ts = [
    "// Generated by spikes/basemap/basemap.py: Natural Earth 1:50m countries (public domain) in the line",
    "// map's projection — x = (lon − LON0)·cos(middle latitude)·K, y = (LAT1 − lat)·K. Do not edit by hand.",
    f"export const MAP = {{ lon0: {LON0}, lat1: {LAT1}, cos: {COS:.6f}, k: {K:.4f}, w: {W}, h: {H} }};",
    "/** Each country's outline; `home` names the three modelled zones. */",
    "export const LAND: { home: string; name: string; d: string }[] = [",
    *[f'  {{ home: "{h}", name: "{n}", d: "{d}" }},' for h, n, d in out],
    "];",
    "",
]
Path("app/src/ui/basemap.ts").write_text("\n".join(ts))
print(f"{len(out)} countries, viewBox {W} x {H}, {Path('app/src/ui/basemap.ts').stat().st_size} bytes")
