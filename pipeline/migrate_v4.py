"""One-off (Stage 2): clone v4's raw cache into this repository, lineage-bearing files only.

Run:  make migrate-v4            (V4=path to the energiamudel-v4 working copy)

SPECIFICATION.md R-DATA-9: a raw file is migrated only if (1) a lineage record names it, (2) it
is in v5's scope (`wanted`, from R-DATA-2 and DECISIONS.md D-002), and (3) the SHA-256 of the
migrated copy equals the record's. The copy is an APFS clone (`cp -c`): no disk space until one
side changes, and raw files never change (fetchers are idempotent). The record is copied
unchanged, so it keeps the original fetch time. Everything not migrated is counted by reason in
the report this writes: docs/research/2026-09-24_v4_migration.md.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

from . import DATA_DIR, ROOT
from .config import BORDERS, ZONES, core_zones

REPORT = ROOT / "docs" / "research" / "2026-09-24_v4_migration.md"
CORE = set(core_zones())
CORE_FI = CORE | {"FI"}
ENTSOE_SCOPE = {           # document type -> zones or borders v5 keeps (R-DATA-2, D-002)
    "A44": set(ZONES), "A65": CORE_FI, "A75": CORE_FI, "A68": CORE_FI, "A71": CORE_FI,
    "A72": {"LV", "LT"}, "A80": CORE, "A25": CORE,
    "A11": set(BORDERS), "A31": set(BORDERS), "A78": set(BORDERS), "A09": set(BORDERS),
}
WHOLE_SOURCES = {"btd", "eex", "worldbank", "tyndp2024", "eraa2025", "catalogue"}
KEEP_DATASETS = {"svk.langsiktig_marknadsanalys_2026"}          # the SvK LMA 2026 report
FINGRID_IDS = {"55", "112", "115"}


def wanted(ds: str) -> tuple[bool, str]:
    """(keep, reason) for one dataset id."""
    p = ds.split(".")
    src = p[0]
    if ds in KEEP_DATASETS:
        return True, "document cited by data/documentary"
    if src == "entsoe":
        doc, where = p[1], p[2]
        return (where in ENTSOE_SCOPE.get(doc, set()),
                f"entsoe {doc} {where}" + ("" if doc in ENTSOE_SCOPE else " (type not used)"))
    if src == "fingrid":
        return p[1] in FINGRID_IDS, f"fingrid dataset {p[1]}"
    if src == "openmeteo":
        return p[2] in CORE, f"openmeteo {p[2]}"
    if src in WHOLE_SOURCES:
        return True, src
    if src == "doc":
        return False, "doc: page records of v4's documentary rows (v5's build writes its own)"
    if src == "pipeline":
        return False, "pipeline: derived records of v4's model (CHP floor, markups)"
    return False, f"source {src} not used by v5"


def _sha(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 22), b""):
            h.update(chunk)
    return h.hexdigest()


def main(v4: str) -> int:
    v4root = Path(v4).resolve()
    raw4, lin4 = v4root / "data" / "raw", v4root / "data" / "lineage"
    raw5, lin5 = DATA_DIR / "raw", DATA_DIR / "lineage"
    files = {f.name.rsplit(".", 1)[0]: f for f in raw4.rglob("*") if f.is_file()
             and not f.name.startswith(".")}
    records = {p.stem: json.loads(p.read_text()) for p in sorted(lin4.glob("*.json"))}
    plan: list[tuple[str, dict, Path]] = []
    skipped: Counter[str] = Counter()
    no_file: Counter[str] = Counter()
    for ds, rec in records.items():
        keep, why = wanted(ds)
        if not keep:
            skipped[why.split(" ")[0] + " " + why.split(" ")[1] if why.startswith("entsoe")
                    else why] += 1
            continue
        if ds not in files:
            no_file[ds.split(".")[0]] += 1
            continue
        plan.append((ds, rec, files[ds]))
    orphans = sorted(stem for stem in files if stem not in records)
    by_dir: dict[Path, list[Path]] = defaultdict(list)
    for _ds, _rec, src in plan:
        dst_dir = raw5 / src.parent.relative_to(raw4)
        if not (dst_dir / src.name).exists():
            by_dir[dst_dir].append(src)
    for dst_dir, srcs in by_dir.items():
        dst_dir.mkdir(parents=True, exist_ok=True)
        for i in range(0, len(srcs), 400):
            subprocess.run(["cp", "-c", *map(str, srcs[i:i + 400]), str(dst_dir)], check=True)
    bad: list[str] = []
    per_source: Counter[str] = Counter()
    size = 0
    for ds, rec, src in plan:
        dst = raw5 / src.relative_to(raw4)
        if rec.get("sha256") and _sha(dst) != rec["sha256"]:
            bad.append(ds)
            dst.unlink()
            continue
        (lin5 / f"{ds}.json").write_text((lin4 / f"{ds}.json").read_text())
        per_source[ds.split(".")[0] if ds.split(".")[0] != "entsoe"
                   else "entsoe " + ds.split(".")[1]] += 1
        size += dst.stat().st_size
    lines = [
        "# v4 raw cache migration (Stage 2)", "",
        "Generated by `make migrate-v4` (`pipeline/migrate_v4.py`); do not edit by hand. "
        f"Source: `{v4root.name}`, `data/raw` and `data/lineage`.", "",
        f"- lineage records in v4: {len(records)}",
        f"- raw files in v4: {len(files)}",
        f"- **migrated: {len(plan) - len(bad)} files, {size / 1e9:.2f} GB**, each with its "
        "record copied unchanged and the SHA-256 of the copy equal to the record's",
        f"- SHA-256 mismatches (not migrated): {len(bad)}" + (f" — {', '.join(bad[:10])}"
                                                               if bad else ""),
        f"- records in scope without a raw file (documentary or derived records, rebuilt by "
        f"`make db`): {sum(no_file.values())} ({dict(no_file)})",
        f"- raw files without a lineage record (never migrated, R-DATA-9): {len(orphans)}"
        + (f" — {', '.join(orphans[:10])}" if orphans else ""), "",
        "## Migrated, by source", "", "| Source | Files |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in sorted(per_source.items())]
    lines += ["", "## Not migrated: out of v5's scope (DECISIONS.md D-002)", "",
              "| Reason | Records |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in sorted(skipped.items())]
    REPORT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:12]))
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1] if len(sys.argv) > 1 else "../energiamudel-v4.nosync"))
